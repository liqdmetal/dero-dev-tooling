//! # tela-toolkit
//!
//! A scaffolding generator for TELA dApps — "create-react-app for DERO's
//! decentralized web." Generates a runnable TELA app skeleton with the
//! encrypted-storage + local-execution model TELA provides.
//!
//! TELA = DERO's Decentralized Web standard: dApp files and data live
//! on-chain, encrypted, and execute locally. This toolkit scaffolds that
//! structure so a developer starts from a working skeleton instead of a
//! blank page.
#![forbid(unsafe_code)]

use serde::Serialize;
use std::fmt;
use std::path::{Path, PathBuf};

/// A generated TELA app scaffold on disk.
#[derive(Debug, Clone)]
pub struct Scaffold {
    /// Root directory of the scaffold.
    pub root: PathBuf,
    /// Files written.
    pub files: Vec<PathBuf>,
}

/// Error writing a scaffold.
#[derive(Debug, thiserror::Error)]
pub enum ScaffoldError {
    /// I/O failure.
    #[error("io error: {0}")]
    Io(#[from] std::io::Error),
    /// The app name cannot safely be used as an identifier or default path.
    #[error("invalid app name `{0}`; use letters, digits, `-`, or `_`")]
    InvalidName(String),
    /// A generated file already exists and overwrite was not enabled.
    #[error("refusing to overwrite existing file: {0}")]
    AlreadyExists(PathBuf),
    /// The manifest could not be serialized.
    #[error("manifest serialization error: {0}")]
    Manifest(#[from] serde_json::Error),
}

impl fmt::Display for Scaffold {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        writeln!(f, "Scaffolded TELA dApp at {}", self.root.display())?;
        for file in &self.files {
            writeln!(f, "  - {}", file.strip_prefix(&self.root).unwrap_or(file).display())?;
        }
        Ok(())
    }
}

/// Generate a TELA dApp scaffold under `dir`.
///
/// Creates:
///   - `tela.json`   — the TELA app manifest (name, version, entry)
///   - `index.html`  — entry point
///   - `app.js`      — the dApp logic stub
///   - `encrypted/`  — placeholder for on-chain encrypted data
pub fn scaffold(dir: &Path, name: &str) -> Result<Scaffold, ScaffoldError> {
    scaffold_with_options(dir, name, false)
}

/// Generate a scaffold, optionally replacing files generated by an earlier run.
///
/// Set `force` only when the caller has explicitly accepted overwriting the
/// generated files in `dir`.
pub fn scaffold_with_options(
    dir: &Path,
    name: &str,
    force: bool,
) -> Result<Scaffold, ScaffoldError> {
    validate_name(name)?;
    let generated = ["tela.json", "index.html", "app.js"];
    if !force {
        if let Some(existing) =
            generated.iter().map(|file| dir.join(file)).find(|path| path.exists())
        {
            return Err(ScaffoldError::AlreadyExists(existing));
        }
    }
    std::fs::create_dir_all(dir)?;
    let mut files = Vec::new();

    #[derive(Serialize)]
    struct Manifest<'a> {
        name: &'a str,
        version: &'a str,
        entry: &'a str,
        engine: &'a str,
        encrypted: [&'a str; 1],
    }
    let manifest = serde_json::to_vec_pretty(&Manifest {
        name,
        version: "0.1.0",
        entry: "index.html",
        engine: "tela",
        encrypted: ["data/"],
    })?;
    let manifest_path = dir.join("tela.json");
    write_generated(&manifest_path, &manifest, force)?;
    files.push(manifest_path);

    let index = r#"<!doctype html>
<html>
<head><meta charset="utf-8"><title>TELA dApp</title></head>
<body>
  <h1>TELA dApp</h1>
  <div id="app"></div>
  <script src="app.js"></script>
</body>
</html>
"#;
    let index_path = dir.join("index.html");
    write_generated(&index_path, index.as_bytes(), force)?;
    files.push(index_path);

    let app = r#"// TELA dApp logic stub — encrypted storage + local execution.
// Data written here is encrypted and stored on-chain (TELA model).
const app = document.getElementById("app");
app.textContent = "Hello from a TELA dApp.";
"#;
    let app_path = dir.join("app.js");
    write_generated(&app_path, app.as_bytes(), force)?;
    files.push(app_path);

    let data_dir = dir.join("encrypted").join("data");
    std::fs::create_dir_all(&data_dir)?;

    Ok(Scaffold { root: dir.to_path_buf(), files })
}

fn validate_name(name: &str) -> Result<(), ScaffoldError> {
    let valid =
        !name.is_empty() && name.chars().all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_');
    if valid {
        Ok(())
    } else {
        Err(ScaffoldError::InvalidName(name.to_string()))
    }
}

fn write_generated(path: &Path, bytes: &[u8], force: bool) -> Result<(), ScaffoldError> {
    if !force && path.exists() {
        return Err(ScaffoldError::AlreadyExists(path.to_path_buf()));
    }
    let tmp = path.with_extension("tmp");
    std::fs::write(&tmp, bytes)?;
    if force && path.exists() {
        std::fs::remove_file(path)?;
    }
    std::fs::rename(tmp, path)?;
    Ok(())
}

/// CLI entrypoint.
pub mod cli {
    use clap::Parser;

    /// Scaffold a new TELA dApp.
    #[derive(Parser)]
    #[command(name = "tela", version, about = "Scaffold a TELA dApp")]
    pub struct Args {
        /// Name of the app.
        #[arg(long, short)]
        pub name: String,
        /// Output directory (defaults to ./name).
        #[arg(long, short)]
        pub out: Option<String>,
        /// Overwrite generated files in an existing scaffold.
        #[arg(long, short)]
        pub force: bool,
    }

    /// Run the CLI.
    pub fn run() -> std::process::ExitCode {
        let args = Args::parse();
        let dir = args.out.clone().unwrap_or_else(|| format!("./{}", args.name));
        match crate::scaffold_with_options(std::path::Path::new(&dir), &args.name, args.force) {
            Ok(s) => {
                println!("{s}");
                std::process::ExitCode::SUCCESS
            }
            Err(e) => {
                eprintln!("error: {e}");
                std::process::ExitCode::FAILURE
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn scaffolds_app() {
        let dir = std::env::temp_dir().join("tela_test_app");
        let _ = std::fs::remove_dir_all(&dir);
        let s = scaffold(&dir, "demo").expect("scaffold ok");
        let manifest = std::fs::read_to_string(dir.join("tela.json")).unwrap();
        assert!(manifest.contains("\"name\": \"demo\""));
        assert!(scaffold(&dir, "demo").is_err());
        scaffold_with_options(&dir, "demo", true).expect("force scaffold ok");
        assert!(dir.join("tela.json").exists());
        assert!(dir.join("index.html").exists());
        assert!(dir.join("app.js").exists());
        assert!(!s.files.is_empty());
        assert!(scaffold(&dir, "bad/name").is_err());
        let _ = std::fs::remove_dir_all(&dir);
    }
}
